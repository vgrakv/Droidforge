  fun importButton() = t("טען מודל מקובץ", "Load a model from a file")
  fun whichModel() = t("איזה מודל זה?", "Which model is this?")
  fun confirmImport(name: String, mb: Long) = t(
    "לטעון את $name מהקובץ שנבחר (כ-${mb}MB)? ההעתקה עשויה לקחת דקה.",
    "Load $name from the selected file (about ${mb}MB)? Copying can take a minute."
  )
  fun importing(name: String, done: Long, total: Long): String {
    val mb = done / (1024 * 1024)
    val size = if (total > 0) " $mb / ${total / (1024 * 1024)} MB" else " $mb MB"
    return t("מעתיק את $name...$size", "Copying $name...$size")
  }
  fun importDone(name: String) = t("$name נטען ומוכן לשימוש.", "$name was loaded and is ready to use.")
  fun importError(e: ImportError, detail: String?) = when (e) {
    ImportError.NOT_A_MODEL -> t(
      "הקובץ לא נראה כמו מודל תקין. צריך קובץ בסיומת .task שהורד במלואו.",
      "The file does not look like a valid model. It must be a fully downloaded .task file."
    )
    ImportError.TOO_SMALL -> t(
      "הקובץ קטן מדי לדגם הזה. כנראה שההורדה לא הושלמה או שנבחר קובץ אחר.",
      "The file is too small for this model. The download is probably incomplete, or it is another file."
    )
    ImportError.NO_SPACE -> t("אין מספיק מקום פנוי במכשיר.", "There is not enough free space on the device.")
    ImportError.CANCELLED -> t("הטעינה בוטלה.", "Loading was cancelled.")
    ImportError.IO -> t("הטעינה נכשלה: ${detail ?: "שגיאה"}", "Loading failed: ${detail ?: "error"}")
  }
  fun cannotReadFile() = t("לא ניתן לקרוא את הקובץ שנבחר.", "The selected file cannot be read.")

