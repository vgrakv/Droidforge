  // ---- model library / browser download dialog ----------------------------------------------

  fun modelSizeText(spec: ModelSpec): String {
    val mb = spec.approxBytes / (1024 * 1024)
    val size = if (mb >= 1024) String.format(java.util.Locale.US, "%.1f GB", mb / 1024.0) else "$mb MB"
    return if (spec.sizeEstimated) t("כ-$size (הערכה)", "about $size (estimate)") else t("כ-$size", "about $size")
  }
