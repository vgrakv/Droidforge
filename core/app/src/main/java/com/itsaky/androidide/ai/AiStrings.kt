  )
  fun downloadInApp() = t("הורד בתוך האפליקציה", "Download in the app")
  fun stateInUse() = t("✓ בשימוש", "✓ in use")
  fun stateInstalled() = t("✓ מותקן (לחץ לשימוש)", "✓ installed (tap to use)")
  fun useThis() = t("השתמש במודל הזה", "Use this model")
