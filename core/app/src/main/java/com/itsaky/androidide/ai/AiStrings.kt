  // ---- model state -------------------------------------------------------------------------

  fun modelMissing() = t("המודלים עדיין לא הותקנו.", "The models are not installed yet.")

  fun modelInstalling(s: ModelState.Downloading): String {
    val mb = s.downloaded / (1024 * 1024)
    val size = if (s.total > 0) " $mb / ${s.total / (1024 * 1024)} MB" else ""
    val verb = if (s.copying) t("מעתיק", "Copying") else t("מוריד", "Downloading")
    return "$verb ${s.name} (${s.step}/${s.steps})$size"
  }

  fun modelReady() = t("המודלים מותקנים ופעילים במכשיר.", "Models are installed and active on this device.")
  fun modelFailed(msg: String) = t("ההתקנה נכשלה: $msg", "Installation failed: $msg")
  fun retry() = t("נסה שוב", "Try again")
  fun downloadNowMobile() = t("הורד עכשיו (גם בנתונים סלולריים)", "Download now (even on mobile data)")

  // ---- fix ---------------------------------------------------------------------------------

  fun proposeFix() = t("הצע תיקון אוטומטי", "Suggest an automatic fix")
  fun fixGenerating() = t("מכין תיקון...", "Preparing a fix...")
  fun fixProposed() = t("תיקון מוצע (בדוק לפני שמחילים):", "Suggested fix (review before applying):")
  fun applyFix() = t("החל תיקון", "Apply fix")
  fun undoFix() = t("בטל תיקון", "Undo fix")
  fun fixApplied() = t("התיקון הוחל על הקובץ.", "The fix was applied to the file.")
  fun fixUndone() = t("התיקון בוטל.", "The fix was undone.")
  fun fixNone(reason: String) = t("המודל חושב שאי אפשר לתקן זאת בעריכת הקובץ: $reason", "The model thinks this cannot be fixed by editing the file: $reason")
  fun fixFailed(msg: String) = t("לא הצלחתי להכין תיקון: $msg", "Could not prepare a fix: $msg")
  fun fixNeedsHeavy() = t("תיקון אוטומטי זמין במצב כבד ובמצב אונליין.", "Automatic fixes are available in heavy and online modes.")
  fun fileChanged() = t("הקובץ השתנה מאז: לא ניתן להחיל.", "The file changed since then: cannot apply.")

  // ---- modes -------------------------------------------------------------------------------

  fun modeName(mode: AiMode) = when (mode) {
    AiMode.NONE -> t("כבוי", "Off")
    AiMode.BASIC -> t("בסיסי", "Basic")
    AiMode.HEBREW -> t("בסיסי + עברית", "Basic + Hebrew")
    AiMode.HEAVY -> t("כבד (תיקון אוטומטי)", "Heavy (auto-fix)")
    AiMode.ONLINE -> t("אונליין", "Online")
  }

  fun modeTitle(mode: AiMode) = when (mode) {
    AiMode.BASIC -> t("1. מודל קטן בלבד", "1. Small model only")
    AiMode.HEBREW -> t("2. מודל קטן + מתרגם לעברית", "2. Small model + Hebrew translator")
    AiMode.HEAVY -> t("3. מודל כבד שמתקן שגיאות בעצמו", "3. Heavy model that fixes errors itself")
    AiMode.ONLINE -> t("4. אונליין עם טוקן", "4. Online with a token")
    AiMode.NONE -> t("בלי AI", "No AI")
  }

  fun modeDescription(mode: AiMode) = when (mode) {
    AiMode.BASIC -> t(
      "מפענח את השגיאה ומסביר אותה באנגלית. מעל התשובה תמיד מופיע הסבר מהיר בעברית. מודל אחד של כ-0.5GB, עובד בלי אינטרנט.",
      "Decodes the error and explains it in English. A quick explanation always appears above it. One model of about 0.5GB, works offline."
    )
    AiMode.HEBREW -> t(
      "כמו מצב 1, ובנוסף מודל שני שמתרגם את ההסבר לעברית טובה יותר. כ-2.1GB בסך הכול. עובד בלי אינטרנט. לא מתקן קוד.",
      "Like mode 1, plus a second model that translates the explanation to better Hebrew. About 2.1GB in total. Works offline. Does not fix code."
    )
    AiMode.HEAVY -> t(
      "מודל גדול אחד (כ-3.9GB) שמפענח בעברית ויודע להציע תיקון לקוד ולהחיל אותו בלחיצה. דורש מכשיר חזק. עובד בלי אינטרנט.",
      "One large model (about 3.9GB) that explains in Hebrew and can suggest a code fix and apply it with one tap. Needs a strong device. Works offline."
    )
    AiMode.ONLINE -> t(
      "משתמש בשירות AI באינטרנט עם הטוקן שלך. אין הורדת מודלים והוא לא מעמיס על המכשיר. פענוח, עברית ותיקון אוטומטי באיכות הגבוהה ביותר. הלוג והקוד סביב השגיאה נשלחים לספק שתבחר.",
      "Uses an online AI service with your own token. No model downloads and no load on the device. Highest quality for decoding, Hebrew and auto-fix. The log and the code around the error are sent to the provider you choose."
    )
    AiMode.NONE -> ""
  }

  // ---- setup screen ------------------------------------------------------------------------

