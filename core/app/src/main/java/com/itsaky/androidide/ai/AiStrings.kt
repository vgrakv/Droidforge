  fun importHeader() = t("יש לי כבר את קובץ המודל", "I already have the model file")
  fun importExplain() = t(
    "אפשר להוריד את הקבצים בעצמך (בדפדפן, בקישורים למטה) ואז לבחור אותם כאן. הקובץ מועתק לאפליקציה, ואחרי הטעינה אפשר למחוק את המקורי. אין צורך באינטרנט.",
    "You can download the files yourself (in a browser, with the links below) and pick them here. The file is copied into the app, and you can delete the original afterwards. No internet needed."
