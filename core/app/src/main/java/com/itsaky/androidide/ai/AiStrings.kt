  fun onlineNeedsToken() = t(
    "מצב אונליין דורש טוקן. פתח את הגדרות ה-AI כדי להגדיר.",
    "Online mode needs a token. Open the AI settings to set it up."
  )
  fun noAiChosen() = t(
    "ה-AI כבוי. אפשר להפעיל אותו בהגדרות ה-AI.",
    "AI is off. You can turn it on in the AI settings."
