package com.itsaky.androidide.ai

import java.util.Locale

/** UI texts of the AI helper: Hebrew for Hebrew locales, English otherwise. */
object AiStrings {

  val lang: AnswerLanguage get() = AnswerLanguage.fromLocaleCode(Locale.getDefault().language)
  val isHebrew: Boolean get() = lang == AnswerLanguage.HEBREW
  private fun t(he: String, en: String) = if (isHebrew) he else en

  // ---- explain tab -------------------------------------------------------------------------

  @JvmStatic
  fun tabTitle(): String = t("הסבר שגיאות", "Explain errors")

  fun emptyHint() = t(
    "כשהבנייה תיכשל, השגיאות יופיעו כאן עם הסבר.",
    "When a build fails, its errors appear here with an explanation."
  )

  fun aiSettings() = t("הגדרות AI", "AI settings")
  fun modeLine(mode: AiMode) = t("מצב: ${modeName(mode)}", "Mode: ${modeName(mode)}")
  fun hintLabel() = t("הסבר מהיר", "Quick explanation")
  fun aiLabel() = t("ניתוח AI", "AI analysis")
  fun waiting() = t("ממתין להתקנת המודל...", "Waiting for the model to be installed...")
  fun running() = t("חושב...", "Thinking...")
  fun translating() = t("מתרגם לעברית...", "Translating to Hebrew...")
  fun failed(msg: String?) = t("ה-AI לא זמין כרגע (${msg ?: "שגיאה"}).", "AI is unavailable right now (${msg ?: "error"}).")
  fun translationFailed() = t("התרגום נכשל, מוצג הנוסח באנגלית.", "Translation failed, showing the English text.")
  fun aiNote(mode: AiMode) = when (mode) {
    AiMode.ONLINE -> t("נוצר על ידי מודל אונליין; ייתכנו טעויות.", "Generated by an online model; it can be wrong.")
